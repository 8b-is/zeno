async function gwSignRs256(claims, privateKeyPem) {
  const der = privateKeyPem
    .replace(/-----BEGIN[^-]+-----/g, "")
    .replace(/-----END[^-]+-----/g, "")
    .replace(/\\s+/g, "");
  const raw = atob(der);
  const keyBytes = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) keyBytes[i] = raw.charCodeAt(i);

  const key = await crypto.subtle.importKey(
    "pkcs8",
    keyBytes,
    { name: "RSASSA-PKCS1-v1_5", hash: "SHA-256" },
    false,
    ["sign"],
  );

  const header = gwB64UrlText(JSON.stringify({ alg: "RS256", typ: "JWT" }));
  const payload = gwB64UrlText(JSON.stringify(claims));
  const signingInput = header + "." + payload;
  const signature = new Uint8Array(
    await crypto.subtle.sign(
      "RSASSA-PKCS1-v1_5",
      key,
      new TextEncoder().encode(signingInput),
    ),
  );
  return signingInput + "." + gwB64Url(signature);
}

