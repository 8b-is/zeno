    id: issuerId + ".zeno_" + gwSanitizeObjectId(accountId),
    classId: issuerId + "." + GW_CLASS_SUFFIX,
    hexBackgroundColor: "#07080b",
    cardTitle: gwLocalized("ZENO 銭"),
    header: gwLocalized(headerValue),
    subheader: gwLocalized("Mobile PASMO · FeliCa NFC-F"),
